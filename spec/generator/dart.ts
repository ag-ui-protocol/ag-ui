const typeName = (name: string): string => TYPE_NAME[name] ?? name;

/** TEXT_MESSAGE_START -> textMessageStart; "tool-call" -> toolCall. */
export function enumMemberName(wire: string): string {
  const parts = wire.toLowerCase().split(/[_-]/);
  return (
    parts[0] +
    parts
      .slice(1)
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join("")
  );
}

function dartString(value: string): string {
  return `'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\$/g, "\\$")}'`;
}

/** A raw string literal: no escapes are interpreted, so none are written. */
function rawDartString(value: string): string {
  if (value.includes("'")) {
    throw new Error(
      `pattern ${value} contains a quote — teach dart.ts a raw string form for it`,
    );
  }
  return `r'${value}'`;
}

function banner(model: ProtocolModel): string {
  return [
    "// @generated by spec/generator — DO NOT EDIT.",
    `// Source: ${model.schemaId}`,
    "// Regenerate: pnpm --filter @ag-ui/spec generate",
    "",
  ].join("\n");
}

/** Wraps a description as a /// doc comment at the given indent. */
function docComment(description: string, indent: string): string {
  const width = WIDTH - indent.length - 4;
  const words = description.split(" ");
  const lines: string[] = [];
  let current = "";
  for (const word of words) {
    const candidate = current === "" ? word : `${current} ${word}`;
    if (candidate.length > width && current !== "") {
      lines.push(current);
      current = word;
    } else {
      current = candidate;
    }
  }
  if (current !== "") lines.push(current);
  return lines.map((line) => `${indent}/// ${line}`).join("\n");
}

