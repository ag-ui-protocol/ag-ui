/**
 * The expression decoding `value` (a Dart expression) at `path` (a Dart
 * expression) into the Dart representation of `type`. `definition` is the
 * Dart expression naming the definition being decoded, for error reports.
 */
function decodeExpr(
  type: TypeExpr,
  value: string,
  path: string,
  depth: number,
  ctx: Context,
): Node {
  const definition = "definition";
  switch (type.kind) {
    case "string":
      return type.pattern !== undefined
        ? call(
            "_stringMatching",
            text(value),
            text(definition),
            text(path),
            text(rawDartString(type.pattern)),
          )
        : call("_string", text(value), text(definition), text(path));
    case "integer": {
      const args = [text(value), text(definition), text(path)];
      if (type.minimum !== undefined) args.push(text(`min: ${type.minimum}`));
      if (type.maximum !== undefined) args.push(text(`max: ${type.maximum}`));
      return call("_int", ...args);
    }
    case "boolean":
      return call("_bool", text(value), text(definition), text(path));
    case "literal":
      // An optional literal is stored, so a document that omits it is encoded
      // without it; its value is still checked.
      return call(
        "_literalValue",
        text(value),
        text(dartString(type.value)),
        text(definition),
        text(path),
      );
    case "any":
      return type.excludeNull
        ? call("_nonNull", text(value), text(definition), text(path))
        : text(value);
    case "openMap":
      return call("_openMap", text(value), text(definition), text(path));
    case "stringEnum":
      return call(
        "_oneOf",
        text(value),
        text(definition),
        text(path),
        collection("const {", "}", type.values.map((v) => text(dartString(v)))),
      );
    case "ref": {
      if (ctx.aliases.has(type.name)) {
        return decodeExpr(resolve(type, ctx), value, path, depth, ctx);
      }
      if (ctx.enums.has(type.name)) {
        return call(
          `${typeName(type.name)}.fromWire`,
          text(value),
          text(definition),
          text(path),
        );
      }
      return call(
        `${typeName(type.name)}.fromJson`,
        call("_object", text(value), text(definition), text(path)),
      );
    }
    case "array": {
      const item = depth === 0 ? "item" : `item${depth}`;
      const itemPath = depth === 0 ? "itemPath" : `itemPath${depth}`;
      const args = [
        text(value),
        text(definition),
        text(path),
        closure(
          `${item}, ${itemPath}`,
          decodeExpr(type.items, item, itemPath, depth + 1, ctx),
        ),
      ];
      if (type.minItems !== undefined) {
        args.push(text(`minItems: ${type.minItems}`));
      }
      return call("_list", ...args);
    }
    case "union":
      if (!isStringOrParts(type)) {
        throw new Error("inline union other than string | ContentPart[]");
      }
      return call("_stringOrParts", text(value), text(definition), text(path));
  }
}

/** Whether `type` serialises as itself, with no conversion. */
function encodesAsIs(type: TypeExpr, ctx: Context): boolean {
  switch (type.kind) {
    case "string":
    case "integer":
    case "boolean":
    case "any":
    case "openMap":
    case "stringEnum":
      return true;
    case "literal":
      return true;
    case "ref":
      if (ctx.aliases.has(type.name)) return encodesAsIs(resolve(type, ctx), ctx);
      return false;
    case "array":
      return encodesAsIs(type.items, ctx);
    case "union":
      return false;
  }
}

/** The expression serialising the non-null Dart value `value` of `type`. */
function encodeExpr(
  type: TypeExpr,
  value: string,
  depth: number,
  ctx: Context,
): string {
  if (encodesAsIs(type, ctx)) return value;
  switch (type.kind) {
    case "ref": {
      if (ctx.aliases.has(type.name)) {
        return encodeExpr(resolve(type, ctx), value, depth, ctx);
      }
      return ctx.enums.has(type.name) ? `${value}.wireName` : `${value}.toJson()`;
    }
    case "array": {
      const element = depth === 0 ? "e" : `e${depth}`;
      return `[for (final ${element} in ${value}) ${encodeExpr(type.items, element, depth + 1, ctx)}]`;
    }
    case "union":
      return `_encodeStringOrParts(${value})`;
    default:
      throw new Error(`unreachable: ${type.kind} encodes as itself`);
  }
}

