function emitEnum(definition: EnumDefinition): string {
  const name = typeName(definition.name);
  const members = definition.values.map(
    (value, index) =>
      `  ${enumMemberName(value)}(${dartString(value)})${index === definition.values.length - 1 ? ";" : ","}`,
  );
  return [
    docComment(definition.description, ""),
    `enum ${name} {`,
    ...members,
    "",
    `  const ${name}(this.wireName);`,
    "",
    "  /// The value as it appears on the wire.",
    "  final String wireName;",
    "",
    "  /// The member for a wire value, or null when there is none.",
    `  static ${name}? tryFromWire(String wire) {`,
    "    for (final member in values) {",
    "      if (member.wireName == wire) return member;",
    "    }",
    "    return null;",
    "  }",
    "",
    "  /// The member for a wire value; an unknown value is a decode error.",
    render(
      collection(
        `static ${name} fromWire(`,
        ")",
        [text("Object? value"), text("String definition"), text("String path")],
      ),
      "  ",
      "",
      " {",
    ),
    "    final wire = _string(value, definition, path);",
    "    return tryFromWire(wire) ??",
    render(
      call(
        "_fail",
        text("definition"),
        text("path"),
        text(`'unknown ${name} value "$wire"'`),
      ),
      "        ",
      "",
      ";",
    ),
    "  }",
    "}",
  ].join("\n");
}

function emitAlias(definition: Definition & { kind: "alias" }, ctx: Context): string {
  return [
    docComment(definition.description, ""),
    `typedef ${typeName(definition.name)} = ${dartType(definition.type, ctx)};`,
  ].join("\n");
}

/** The fields every member of a union declares alike: name, type, requiredness. */
function commonFields(union: UnionDefinition, ctx: Context): Field[] {
  const members = union.members.map((member) => {
    const object = ctx.objects.get(member);
    if (!object) throw new Error(`${union.name} member ${member} is not an object`);
    return object;
  });
  const [first, ...rest] = members;
  return first.fields.filter((field) =>
    rest.every((member) =>
      member.fields.some(
        (candidate) =>
          candidate.name === field.name &&
          candidate.required === field.required &&
          fieldType(candidate, ctx) === fieldType(field, ctx),
      ),
    ),
  );
}

/** The mixins every member of a union composes. */
function commonMixins(union: UnionDefinition, ctx: Context): string[] {
  const members = union.members.map((member) => ctx.objects.get(member)!);
  const [first, ...rest] = members;
  return first.composedMixins.filter((mixin) =>
    rest.every((member) => member.composedMixins.includes(mixin)),
  );
}

function mixinFieldNames(mixins: string[], ctx: Context): Set<string> {
  const names = new Set<string>();
  for (const mixin of mixins) {
    const shape = ctx.model.mixinShapes.find((entry) => entry.name === mixin);
    if (!shape) throw new Error(`no mixin shape named ${mixin}`);
    for (const field of shape.fields) names.add(field.name);
  }
  return names;
}

function emitMixin(shape: ObjectDefinition, ctx: Context): string {
  const getters = shape.fields.map((field) =>
    [
      docComment(field.description, "  "),
      `  ${fieldType(field, ctx)} get ${field.name};`,
    ].join("\n"),
  );
  return [
    docComment(shape.description, ""),
    `abstract interface class ${typeName(shape.name)} {`,
    getters.join("\n\n"),
    "}",
  ].join("\n");
}

function emitUnion(definition: UnionDefinition, ctx: Context): string {
  const name = typeName(definition.name);
  const mixins = commonMixins(definition, ctx);
  const covered = mixinFieldNames(mixins, ctx);
  const implementsClause =
    mixins.length > 0 ? ` implements ${mixins.map(typeName).join(", ")}` : "";
  const getters = commonFields(definition, ctx)
    .filter((field) => !covered.has(field.name))
    .flatMap((field) => [
      "",
      docComment(field.description, "  "),
      `  ${fieldType(field, ctx)} get ${field.name};`,
    ]);
  const discriminator = definition.discriminator;
  if (discriminator === undefined) {
    throw new Error(
      `union ${definition.name} has no discriminator — teach dart.ts how to decode a tagless union`,
    );
  }
  const arms = definition.members.map((member) => {
    const object = ctx.objects.get(member)!;
    const tag = object.fields.find((field) => field.name === discriminator);
    if (!tag || tag.type.kind !== "literal") {
      throw new Error(`${member} does not pin ${discriminator}`);
    }
    return render(
      labeled(
        `${dartString(tag.type.value)} => `,
        call(`${typeName(member)}.fromJson`, text("json")),
      ),
      "      ",
      "",
      ",",
    );
  });
  return [
    docComment(definition.description, ""),
    `sealed class ${name}${implementsClause} {`,
    `  const ${name}();`,
    "",
    `  /// Decodes a document by its \`${discriminator}\` discriminator.`,
    `  factory ${name}.fromJson(Map<String, Object?> json) {`,
    `    _require(json, ${dartString(definition.name)}, ${dartString(discriminator)});`,
    `    final tag = json[${dartString(discriminator)}];`,
    "    return switch (tag) {",
    ...arms,
    `      _ => _unknownTag(${dartString(definition.name)}, '/${discriminator}', tag),`,
    "    };",
    "  }",
    ...getters,
    "",
    "  /// The wire form of this value.",
    "  Map<String, Object?> toJson();",
    "}",
  ].join("\n");
}

function emitObject(definition: ObjectDefinition, ctx: Context): string {
  const name = typeName(definition.name);
  for (const field of definition.fields) {
    if (DART_RESERVED.has(field.name) || DART_MEMBER_NAMES.has(field.name)) {
      throw new Error(
        `field ${definition.name}.${field.name} is a Dart reserved word or a member every generated class has — add a rename before the schema relies on it`,
      );
    }
  }
  const union = ctx.unionOf.get(definition.name);
  const inheritedMixins =
    union !== undefined ? commonMixins(ctx.unions.get(union)!, ctx) : [];
  const ownMixins = definition.composedMixins.filter(
    (mixin) => !inheritedMixins.includes(mixin),
  );
  const unionCommon =
    union !== undefined
      ? new Set(commonFields(ctx.unions.get(union)!, ctx).map((f) => f.name))
      : new Set<string>();
  const overridden = new Set([
    ...mixinFieldNames(definition.composedMixins, ctx),
    ...unionCommon,
  ]);
  const header =
    `final class ${name}` +
    (union !== undefined ? ` extends ${typeName(union)}` : "") +
    (ownMixins.length > 0 ? ` implements ${ownMixins.map(typeName).join(", ")}` : "") +
    " {";

  // A required literal is a getter: the only possible value is supplied, so
  // constructors never spell the discriminator. An optional literal is stored,
  // because whether it was present is information the wire form keeps.
  const literals = definition.fields.filter(
    (field) => field.type.kind === "literal" && field.required,
  );
  const stored = definition.fields.filter(
    (field) => !(field.type.kind === "literal" && field.required),
  );

  // An open object (the RFC 6902 operations) keeps the members it does not
  // define, because the RFC requires them to be ignored rather than rejected
  // and a re-serialising intermediary must not lose them.
  const open = !definition.closed;
  if (open && definition.fields.some((field) => field.name === "extras")) {
    throw new Error(
      `${definition.name} is open and has a field named extras — rename the carrier in dart.ts`,
    );
  }

  // Constructor.
  const params = stored.map((field) =>
    text(field.required ? `required this.${field.name}` : `this.${field.name}`),
  );
  if (open) params.push(text("this.extras = const {}"));
  const constructor = render(
    params.length === 0
      ? text(`const ${name}()`)
      : collection(`const ${name}({`, "})", params),
    "  ",
    "",
    ";",
  );

  // fromJson.
  const fromJsonLines: string[] = [
    "  /// Decodes a document; throws [AguiDecodeException] when it does not match.",
    `  factory ${name}.fromJson(Map<String, Object?> json) {`,
    `    const definition = ${dartString(definition.name)};`,
  ];
  for (const field of literals) {
    if (field.type.kind !== "literal") continue;
    fromJsonLines.push(
      render(
        call(
          "_literal",
          text(`json[${dartString(field.name)}]`),
          text(dartString(field.type.value)),
          text("definition"),
          text(`'/${field.name}'`),
        ),
        "    ",
        "",
        ";",
      ),
    );
  }
  for (const field of stored) {
    if (field.required) {
      fromJsonLines.push(
        `    _require(json, definition, ${dartString(field.name)});`,
      );
    }
  }
  const args = stored.map((field) => {
    const path = `'/${field.name}'`;
    if (field.required) {
      return render(
        decodeExpr(
          field.type,
          `json[${dartString(field.name)}]`,
          path,
          0,
          ctx,
        ),
        "      ",
        `${field.name}: `,
        ",",
      );
    }
    return render(
      call(
        "_opt",
        text("json"),
        text(dartString(field.name)),
        closure("v", decodeExpr(field.type, "v", path, 0, ctx)),
      ),
      "      ",
      `${field.name}: `,
      ",",
    );
  });
  if (open) {
    args.push(
      render(
        call(
          "_extras",
          text("json"),
          collection(
            "const {",
            "}",
            definition.fields.map((field) => text(dartString(field.name))),
          ),
        ),
        "      ",
        "extras: ",
        ",",
      ),
    );
  }
  if (args.length === 0) {
    fromJsonLines.push(`    return const ${name}();`);
  } else {
    fromJsonLines.push(`    return ${name}(`, ...args, "    );");
  }
  fromJsonLines.push("  }");

  // Literal getters and stored fields.
  const members: string[] = [];
  for (const field of literals) {
    if (field.type.kind !== "literal") continue;
    const value =
      field.type.enumRef !== undefined
        ? `${typeName(field.type.enumRef)}.${enumMemberName(field.type.value)}`
        : dartString(field.type.value);
    const type = dartType(field.type, ctx);
    members.push(
      "",
      docComment(field.description, "  "),
      ...(overridden.has(field.name) ? ["  @override"] : []),
      `  ${type} get ${field.name} => ${value};`,
    );
  }
  for (const field of stored) {
    const description =
      field.type.kind === "array" && field.type.itemsDescription !== undefined
        ? `${field.description} Each item: ${field.type.itemsDescription}`
        : field.description;
    const notes: string[] = [];
    if (field.defaultValue !== undefined) {
      notes.push(`Default: ${JSON.stringify(field.defaultValue)}.`);
    }
    if (field.contentEncoding !== undefined) {
      notes.push(`Content encoding: ${field.contentEncoding}.`);
    }
    members.push(
      "",
      docComment([description, ...notes].join(" "), "  "),
      ...(overridden.has(field.name) ? ["  @override"] : []),
      `  final ${fieldType(field, ctx)} ${field.name};`,
    );
  }

  if (open) {
    members.push(
      "",
      "  /// Members the protocol does not define on this open object, kept",
      "  /// verbatim: RFC 6902 requires them to be ignored, not rejected.",
      "  final Map<String, Object?> extras;",
    );
  }

  // toJson.
  const entries: Node[] = [];
  for (const field of literals) {
    if (field.type.kind !== "literal") continue;
    const value =
      field.type.enumRef !== undefined
        ? `${field.name}.wireName`
        : field.name;
    entries.push(text(`${dartString(field.name)}: ${value}`));
  }
  for (const field of stored) {
    const key = dartString(field.name);
    if (field.required) {
      entries.push(text(`${key}: ${encodeExpr(field.type, field.name, 0, ctx)}`));
      continue;
    }
    const value = encodesAsIs(field.type, ctx)
      ? field.name
      : field.type.kind === "array"
        ? encodeExpr(field.type, `${field.name}!`, 0, ctx)
        : field.type.kind === "union"
          ? `_encodeStringOrParts(${field.name}!)`
          : ctx.enums.has((field.type as { name?: string }).name ?? "")
            ? `${field.name}?.wireName`
            : `${field.name}?.toJson()`;
    entries.push(guarded(`${field.name} != null`, text(`${key}: ${value}`)));
  }
  if (open) entries.push(text("...extras"));
  const toJson = render(
    collection("{", "}", entries),
    "  ",
    "Map<String, Object?> toJson() => ",
    ";",
  );

  return [
    docComment(definition.description, ""),
    header,
    constructor,
    "",
    ...fromJsonLines,
    ...members,
    "",
    "  /// The wire form of this value.",
    ...(union !== undefined ? ["  @override"] : []),
    toJson,
    "}",
  ].join("\n");
}

function emitDefinition(definition: Definition, ctx: Context): string {
  switch (definition.kind) {
    case "enum":
      return emitEnum(definition);
    case "alias":
      return emitAlias(definition, ctx);
    case "union":
      return emitUnion(definition, ctx);
    case "object":
      return emitObject(definition, ctx);
  }
}

export function emitModels(model: ProtocolModel): string {
  const ctx = buildContext(model);
  const mixins = model.mixinShapes.map((shape) => emitMixin(shape, ctx));
  const definitions = model.definitions.map((definition) =>
    emitDefinition(definition, ctx),
  );
  return [`${banner(model)}\n${PREAMBLE.trimEnd()}`, ...mixins, ...definitions]
    .join("\n\n")
    .concat("\n");
}

export function emitVersion(model: ProtocolModel): string {
  return [
    banner(model),
    docComment(
      `The protocol version this code was generated from: the version segment of the schema's $id (${model.schemaId}). Never typed by a human.`,
      "",
    ),
    `const String protocolVersion = ${dartString(model.version)};`,
    "",
  ].join("\n");
}

