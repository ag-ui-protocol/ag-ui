interface Context {
  model: ProtocolModel;
  aliases: Map<string, TypeExpr>;
  enums: Map<string, EnumDefinition>;
  objects: Map<string, ObjectDefinition>;
  unions: Map<string, UnionDefinition>;
  /** Object name -> the one union it belongs to. */
  unionOf: Map<string, string>;
}

function buildContext(model: ProtocolModel): Context {
  const aliases = new Map<string, TypeExpr>();
  const enums = new Map<string, EnumDefinition>();
  const objects = new Map<string, ObjectDefinition>();
  const unions = new Map<string, UnionDefinition>();
  const unionOf = new Map<string, string>();
  for (const definition of model.definitions) {
    switch (definition.kind) {
      case "alias":
        aliases.set(definition.name, definition.type);
        break;
      case "enum":
        enums.set(definition.name, definition);
        break;
      case "object":
        objects.set(definition.name, definition);
        break;
      case "union":
        unions.set(definition.name, definition);
        for (const member of definition.members) {
          const existing = unionOf.get(member);
          if (existing !== undefined) {
            throw new Error(
              `${member} is a member of both ${existing} and ${definition.name} — ` +
                "a Dart class extends one sealed class; teach dart.ts a second strategy before the schema relies on it",
            );
          }
          unionOf.set(member, definition.name);
        }
        break;
    }
  }
  return { model, aliases, enums, objects, unions, unionOf };
}

/** Follows alias references down to the type that carries the shape. */
function resolve(type: TypeExpr, ctx: Context): TypeExpr {
  if (type.kind === "ref") {
    const alias = ctx.aliases.get(type.name);
    if (alias !== undefined) {
      const target = resolve(alias, ctx);
      return type.excludeNull && target.kind === "any"
        ? { ...target, excludeNull: true }
        : target;
    }
  }
  return type;
}

function isStringOrParts(type: TypeExpr): boolean {
  return JSON.stringify(type) === JSON.stringify(STRING_OR_PARTS);
}

/** The Dart type for a field's TypeExpr, before nullability. */
function dartType(type: TypeExpr, ctx: Context): string {
  switch (type.kind) {
    case "string":
      return "String";
    case "integer":
      return "int";
    case "boolean":
      return "bool";
    case "literal":
      return type.enumRef !== undefined ? typeName(type.enumRef) : "String";
    case "any":
      return type.excludeNull ? "Object" : "Object?";
    case "openMap":
      return "Map<String, Object?>";
    case "stringEnum":
      return "String";
    case "ref": {
      // An alias to a nullable JSON value, referenced with null excluded, is
      // the non-null Object: the typedef cannot say so, so the field does.
      const resolved = resolve(type, ctx);
      if (ctx.aliases.has(type.name) && resolved.kind === "any") {
        return dartType(resolved, ctx);
      }
      return typeName(type.name);
    }
    case "array":
      return `List<${dartType(type.items, ctx)}>`;
    case "union":
      if (!isStringOrParts(type)) {
        throw new Error(
          `inline union ${JSON.stringify(type)} is not the string | ContentPart[] shape — teach dart.ts how to represent it`,
        );
      }
      return "Object";
  }
}

/** The declared type of a field: nullable when optional, unless already so. */
function fieldType(field: Field, ctx: Context): string {
  const base = dartType(field.type, ctx);
  if (field.required || base.endsWith("?")) return base;
  return `${base}?`;
}

