type Node =
  | { kind: "text"; text: string }
  | { kind: "call"; head: string; args: Node[] }
  | { kind: "closure"; params: string; body: Node }
  | { kind: "collection"; open: string; close: string; entries: Node[] }
  | { kind: "labeled"; label: string; node: Node }
  | { kind: "guarded"; guard: string; node: Node };

const text = (value: string): Node => ({ kind: "text", text: value });
const labeled = (label: string, node: Node): Node => ({
  kind: "labeled",
  label,
  node,
});
/** A collection-if element: `if (guard) entry`, split after the guard. */
const guarded = (guard: string, node: Node): Node => ({
  kind: "guarded",
  guard,
  node,
});
const call = (head: string, ...args: Node[]): Node => ({
  kind: "call",
  head,
  args,
});
const closure = (params: string, body: Node): Node => ({
  kind: "closure",
  params,
  body,
});
const collection = (open: string, close: string, entries: Node[]): Node => ({
  kind: "collection",
  open,
  close,
  entries,
});

function flat(node: Node): string {
  switch (node.kind) {
    case "text":
      return node.text;
    case "call":
      return `${node.head}(${node.args.map(flat).join(", ")})`;
    case "closure":
      return `(${node.params}) => ${flat(node.body)}`;
    case "collection":
      return `${node.open}${node.entries.map(flat).join(", ")}${node.close}`;
    case "labeled":
      return `${node.label}${flat(node.node)}`;
    case "guarded":
      return `if (${node.guard}) ${flat(node.node)}`;
  }
}

/**
 * Renders `prefix + node + suffix` starting at `indent`, on one line when the
 * whole thing fits in the width and split otherwise. A split call or
 * collection puts each element on its own line with a trailing comma; a
 * split closure keeps its parameters on the first line and splits its body.
 */
function render(
  node: Node,
  indent: string,
  prefix = "",
  suffix = "",
): string {
  const oneLine = `${indent}${prefix}${flat(node)}${suffix}`;
  if (oneLine.length <= WIDTH) return oneLine;
  const inner = `${indent}  `;
  switch (node.kind) {
    case "text":
      return oneLine;
    case "call": {
      if (node.args.length === 0) return oneLine;
      // A collection argument is "block formatted" when the arguments before
      // it fit on the opening line and the arguments after it fit on the
      // closing line: the call stays on one line, the entries get the split.
      const isCollection = (arg: Node): boolean =>
        (arg.kind === "collection" && arg.entries.length > 0) ||
        (arg.kind === "labeled" && isCollection(arg.node));
      const collections = node.args.filter(isCollection);
      const blockIndex =
        collections.length === 1 ? node.args.indexOf(collections[0]) : -1;
      if (blockIndex !== -1) {
        const block = node.args[blockIndex];
        if (block.kind !== "collection") {
          // A labeled collection (`optional: {…}`) never block-formats; it
          // falls through to the ordinary split below.
          return [
            `${indent}${prefix}${node.head}(`,
            ...node.args.map((arg) => render(arg, inner, "", ",")),
            `${indent})${suffix}`,
          ].join("\n");
        }
        const before = node.args.slice(0, blockIndex).map(flat);
        const after = node.args.slice(blockIndex + 1).map(flat);
        const open = `${indent}${prefix}${node.head}(${[...before, block.open].join(", ")}`;
        const close = `${indent}${[block.close, ...after].join(", ")})${suffix}`;
        if (open.length <= WIDTH && close.length <= WIDTH) {
          return [
            open,
            ...block.entries.map((entry) => render(entry, inner, "", ",")),
            close,
          ].join("\n");
        }
      }
      return [
        `${indent}${prefix}${node.head}(`,
        ...node.args.map((arg) => render(arg, inner, "", ",")),
        `${indent})${suffix}`,
      ].join("\n");
    }
    case "closure":
      // A function expression splits after its arrow, with the body four
      // columns in, when the body then fits on one line; otherwise the arrow
      // stays put and the body itself splits.
      {
        const hanging = `${indent}    ${flat(node.body)}${suffix}`;
        if (hanging.length <= WIDTH) {
          return [`${indent}${prefix}(${node.params}) =>`, hanging].join("\n");
        }
        return render(node.body, indent, `${prefix}(${node.params}) => `, suffix);
      }
    case "labeled":
      return render(node.node, indent, `${prefix}${node.label}`, suffix);
    case "guarded":
      return [
        `${indent}${prefix}if (${node.guard})`,
        render(node.node, inner, "", suffix),
      ].join("\n");
    case "collection":
      if (node.entries.length === 0) return oneLine;
      return [
        `${indent}${prefix}${node.open}`,
        ...node.entries.map((entry) => render(entry, inner, "", ",")),
        `${indent}${node.close}${suffix}`,
      ].join("\n");
  }
}

