/* Shapes: the model as Dart data, for the enforcement stage's strip    */
/* ------------------------------------------------------------------ */

const SHAPE_CLASSES = `/// A node of the protocol's shape, for walking a document without decoding it.
sealed class Shape {
  const Shape();
}

/// An object definition: field name -> shape. \`closed\` is false for the
/// RFC 6902 operations, which keep members they do not define.
final class ObjectShape extends Shape {
  const ObjectShape(
    this.name,
    this.fields, {
    this.optional = const <String>{},
    this.closed = true,
  });

  final String name;
  final Map<String, Shape> fields;

  /// The fields a document may leave out.
  final Set<String> optional;
  final bool closed;
}

/// A discriminated union: tag value -> member definition name.
final class UnionShape extends Shape {
  const UnionShape(this.name, this.discriminator, this.members);

  final String name;
  final String discriminator;
  final Map<String, String> members;
}

/// A reference to another entry of [shapes].
final class RefShape extends Shape {
  const RefShape(this.name);

  final String name;
}

/// An array of one shape.
final class ListShape extends Shape {
  const ListShape(this.items);

  final Shape items;
}

/// One of several shapes, chosen by the JSON kind of the value: the inline
/// \`string | ContentPart[]\` union.
final class ChoiceShape extends Shape {
  const ChoiceShape(this.options);

  final List<Shape> options;
}

/// A leaf: scalar, enum, literal, any, open map. Nothing inside is inspected.
final class OpaqueShape extends Shape {
  const OpaqueShape();
}`;

function shapeNode(type: TypeExpr): Node {
  switch (type.kind) {
    case "ref":
      return text(`RefShape(${dartString(type.name)})`);
    case "array":
      return call("ListShape", shapeNode(type.items));
    case "union":
      return call(
        "ChoiceShape",
        collection("[", "]", type.members.map(shapeNode)),
      );
    default:
      return text("OpaqueShape()");
  }
}

export function emitShapes(model: ProtocolModel): string {
  const entries = model.definitions.map((definition) => {
    const key = dartString(definition.name);
    switch (definition.kind) {
      case "object": {
        const fields = collection(
          "{",
          "}",
          definition.fields.map((field) =>
            labeled(`${dartString(field.name)}: `, shapeNode(field.type)),
          ),
        );
        const args = [text(key), fields];
        const optional = definition.fields.filter((field) => !field.required);
        if (optional.length > 0) {
          args.push(
            labeled(
              "optional: ",
              collection(
                "{",
                "}",
                optional.map((field) => text(dartString(field.name))),
              ),
            ),
          );
        }
        if (!definition.closed) args.push(text("closed: false"));
        return render(call("ObjectShape", ...args), "  ", `${key}: `, ",");
      }
      case "union": {
        if (definition.discriminator === undefined) {
          throw new Error(`union ${definition.name} has no discriminator`);
        }
        const members = definition.members.map((member) => {
          const object = model.definitions.find(
            (d): d is ObjectDefinition => d.kind === "object" && d.name === member,
          )!;
          const tag = object.fields.find(
            (field) => field.name === definition.discriminator,
          )!;
          if (tag.type.kind !== "literal") throw new Error("non-literal tag");
          return text(`${dartString(tag.type.value)}: ${dartString(member)}`);
        });
        return render(
          call(
            "UnionShape",
            text(key),
            text(dartString(definition.discriminator)),
            collection("{", "}", members),
          ),
          "  ",
          `${key}: `,
          ",",
        );
      }
      case "enum":
        return `  ${key}: OpaqueShape(),`;
      case "alias":
        return render(shapeNode(definition.type), "  ", `${key}: `, ",");
    }
  });
  return [
    banner(model),
    SHAPE_CLASSES,
    "",
    "/// Every definition's shape, by name.",
    "const Map<String, Shape> shapes = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

export function emitDart(model: ProtocolModel): DartFile[] {
  assertTableKeys("TYPE_NAME", Object.keys(TYPE_NAME), model);
  return [
    { name: "models.dart", content: emitModels(model) },
    { name: "shapes.dart", content: emitShapes(model) },
    { name: "version.dart", content: emitVersion(model) },
  ];
}
