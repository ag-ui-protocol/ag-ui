/**
 * The Dart emitter: protocol model in, the agui package's generated types out.
 *
 * Dart idiom only — the model already resolved everything. Immutable final
 * classes with named constructor parameters, Dart 3 sealed classes for the
 * unions, enums with wire names, typedefs for the aliases, and a hand-rolled
 * fromJson/toJson on every object: no build_runner and no second generator,
 * so the schema stays the single source of truth for the wire shape.
 *
 * Decoding is strict in the way the generated zod schemas are: unknown keys
 * are ignored (the enforcement stage strips and warns), null on an optional
 * field is a type error (the compatibility boundary converts the tolerated
 * ones first), and a missing required field, a wrong type, an unknown enum
 * value or an unknown discriminator throws AguiDecodeException.
 *
 * The output is emitted already in `dart format`'s shape (the 3.7+ "tall"
 * style at 80 columns), because the generator runs under Node and cannot call
 * the formatter: a small layout helper below decides, per expression, whether
 * it fits on one line or splits with a trailing comma, which is the one rule
 * that style applies everywhere this file needs it. The Dart package's CI
 * runs the real formatter over the output with a pinned SDK and fails on any
 * difference, so a divergence between the helper and the formatter is caught
 * there rather than silently committed.
 *
 * If a field's meaning ever appears in this file, it has escaped the schema.
 */

